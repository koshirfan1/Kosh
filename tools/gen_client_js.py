#!/usr/bin/env python3
"""Regenerates packages/webi/client_js.kh from packages/webi/client/webi.js.

The webi server serves the browser client from /_webi/client.js. Kosh
packages cannot locate their own data files at runtime, so the script is
embedded as a Kosh string constant. Run this after editing webi.js:

    python3 tools/gen_client_js.py

tests/test_webi_client_serve.kh fails if the two ever drift apart.
"""
import hashlib, os, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
src = os.path.join(root, "packages", "webi", "client", "webi.js")
dst = os.path.join(root, "packages", "webi", "client_js.kh")

js = open(src, encoding="utf-8", newline="").read().replace("\r\n", "\n")
js.encode("ascii")      # the client is kept ASCII-only on purpose (no encoding surprises)
if "\r" in js:
    sys.exit("webi.js contains a bare CR")

esc = js.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
digest = hashlib.sha256(js.encode("ascii")).hexdigest()

out = (
    "# GENERATED by tools/gen_client_js.py from client/webi.js - DO NOT EDIT.\n"
    "# Edit client/webi.js, then run: python3 tools/gen_client_js.py\n"
    "\n"
    "let WEBI_CLIENT_JS = \"" + esc + "\"\n"
    "let WEBI_CLIENT_JS_SHA256 = \"" + digest + "\"\n"
)
open(dst, "w", encoding="utf-8", newline="\n").write(out)
print("wrote", os.path.relpath(dst, root), len(js), "bytes of JS, sha256", digest)
