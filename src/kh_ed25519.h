/* ---- SHA-512 ----------------------------------------------------------- */
typedef struct { uint64_t h[8]; uint64_t len; uint8_t buf[128]; size_t n; } sha512_ctx;

#define ROR64(x, n) (((x) >> (n)) | ((x) << (64 - (n))))

static void sha512_block(sha512_ctx *c, const uint8_t *p) {
    uint64_t w[80], a, b, cc, d, e, f, g, h, t1, t2;
    for (int i = 0; i < 16; i++) {
        w[i] = 0;
        for (int j = 0; j < 8; j++) w[i] = (w[i] << 8) | p[i * 8 + j];
    }
    for (int i = 16; i < 80; i++) {
        uint64_t s0 = ROR64(w[i-15], 1) ^ ROR64(w[i-15], 8) ^ (w[i-15] >> 7);
        uint64_t s1 = ROR64(w[i-2], 19) ^ ROR64(w[i-2], 61) ^ (w[i-2] >> 6);
        w[i] = w[i-16] + s0 + w[i-7] + s1;
    }
    a = c->h[0]; b = c->h[1]; cc = c->h[2]; d = c->h[3];
    e = c->h[4]; f = c->h[5]; g = c->h[6]; h = c->h[7];
    for (int i = 0; i < 80; i++) {
        uint64_t S1 = ROR64(e, 14) ^ ROR64(e, 18) ^ ROR64(e, 41);
        uint64_t ch = (e & f) ^ (~e & g);
        t1 = h + S1 + ch + SHA512_K[i] + w[i];
        uint64_t S0 = ROR64(a, 28) ^ ROR64(a, 34) ^ ROR64(a, 39);
        uint64_t mj = (a & b) ^ (a & cc) ^ (b & cc);
        t2 = S0 + mj;
        h = g; g = f; f = e; e = d + t1; d = cc; cc = b; b = a; a = t1 + t2;
    }
    c->h[0] += a; c->h[1] += b; c->h[2] += cc; c->h[3] += d;
    c->h[4] += e; c->h[5] += f; c->h[6] += g; c->h[7] += h;
}

static void sha512_init(sha512_ctx *c) {
    memcpy(c->h, SHA512_H0, sizeof(c->h));
    c->len = 0; c->n = 0;
}

static void sha512_update(sha512_ctx *c, const uint8_t *d, size_t len) {
    c->len += len;
    while (len) {
        size_t take = 128 - c->n;
        if (take > len) take = len;
        memcpy(c->buf + c->n, d, take);
        c->n += take; d += take; len -= take;
        if (c->n == 128) { sha512_block(c, c->buf); c->n = 0; }
    }
}

static void sha512_final(sha512_ctx *c, uint8_t out[64]) {
    uint64_t bits = c->len * 8;          /* messages here are far below 2^61 bytes */
    uint8_t pad = 0x80, zero = 0;
    sha512_update(c, &pad, 1);
    while (c->n != 112) sha512_update(c, &zero, 1);
    for (int i = 0; i < 8; i++) sha512_update(c, &zero, 1);   /* high 64 bits of the length */
    uint8_t lb[8];
    for (int i = 0; i < 8; i++) lb[i] = (uint8_t)(bits >> (56 - 8 * i));
    sha512_update(c, lb, 8);
    for (int i = 0; i < 8; i++)
        for (int j = 0; j < 8; j++) out[i * 8 + j] = (uint8_t)(c->h[i] >> (56 - 8 * j));
}

/* ---- field arithmetic mod 2^255-19 ------------------------------------- */
static void ed_set25519(gf r, const gf a) { for (int i = 0; i < 16; i++) r[i] = a[i]; }

static void ed_car25519(gf o) {
    int64_t c;
    for (int i = 0; i < 16; i++) {
        o[i] += (1LL << 16);
        c = o[i] >> 16;
        o[(i + 1) * (i < 15)] += c - 1 + 37 * (c - 1) * (i == 15);
        o[i] -= c * 65536;   /* (not "<<": c can be negative, and shifting a negative value is undefined in C) */
    }
}

static void ed_sel25519(gf p, gf q, int b) {
    int64_t t, c = ~(int64_t)(b - 1);
    for (int i = 0; i < 16; i++) { t = c & (p[i] ^ q[i]); p[i] ^= t; q[i] ^= t; }
}

static void ed_pack25519(uint8_t *o, const gf n) {
    int i, j, b;
    gf m, t;
    for (i = 0; i < 16; i++) t[i] = n[i];
    ed_car25519(t); ed_car25519(t); ed_car25519(t);
    for (j = 0; j < 2; j++) {
        m[0] = t[0] - 0xffed;
        for (i = 1; i < 15; i++) {
            m[i] = t[i] - 0xffff - ((m[i-1] >> 16) & 1);
            m[i-1] &= 0xffff;
        }
        m[15] = t[15] - 0x7fff - ((m[14] >> 16) & 1);
        b = (int)((m[15] >> 16) & 1);
        m[14] &= 0xffff;
        ed_sel25519(t, m, 1 - b);
    }
    for (i = 0; i < 16; i++) { o[2*i] = (uint8_t)(t[i] & 0xff); o[2*i+1] = (uint8_t)(t[i] >> 8); }
}

static int ed_verify32(const uint8_t *x, const uint8_t *y) {
    uint32_t d = 0;
    for (int i = 0; i < 32; i++) d |= x[i] ^ y[i];
    return (int)((1 & ((d - 1) >> 8)) - 1);          /* 0 if equal, -1 otherwise */
}

static int ed_neq25519(const gf a, const gf b) {
    uint8_t c[32], d[32];
    ed_pack25519(c, a); ed_pack25519(d, b);
    return ed_verify32(c, d);
}

static uint8_t ed_par25519(const gf a) { uint8_t d[32]; ed_pack25519(d, a); return d[0] & 1; }

static void ed_unpack25519(gf o, const uint8_t *n) {
    for (int i = 0; i < 16; i++) o[i] = n[2*i] + ((int64_t)n[2*i+1] << 8);
    o[15] &= 0x7fff;
}

static void ed_A(gf o, const gf a, const gf b) { for (int i = 0; i < 16; i++) o[i] = a[i] + b[i]; }
static void ed_Z(gf o, const gf a, const gf b) { for (int i = 0; i < 16; i++) o[i] = a[i] - b[i]; }

static void ed_M(gf o, const gf a, const gf b) {
    int64_t t[31];
    for (int i = 0; i < 31; i++) t[i] = 0;
    for (int i = 0; i < 16; i++) for (int j = 0; j < 16; j++) t[i+j] += a[i] * b[j];
    for (int i = 0; i < 15; i++) t[i] += 38 * t[i+16];
    for (int i = 0; i < 16; i++) o[i] = t[i];
    ed_car25519(o); ed_car25519(o);
}

static void ed_S(gf o, const gf a) { ed_M(o, a, a); }

static void ed_inv25519(gf o, const gf i) {
    gf c;
    for (int a = 0; a < 16; a++) c[a] = i[a];
    for (int a = 253; a >= 0; a--) { ed_S(c, c); if (a != 2 && a != 4) ed_M(c, c, i); }
    for (int a = 0; a < 16; a++) o[a] = c[a];
}

static void ed_pow2523(gf o, const gf i) {
    gf c;
    for (int a = 0; a < 16; a++) c[a] = i[a];
    for (int a = 250; a >= 0; a--) { ed_S(c, c); if (a != 1) ed_M(c, c, i); }
    for (int a = 0; a < 16; a++) o[a] = c[a];
}

/* ---- group operations (extended coordinates) --------------------------- */
static void ed_add(gf p[4], gf q[4]) {
    gf a, b, c, d, t, e, f, g, h;
    ed_Z(a, p[1], p[0]); ed_Z(t, q[1], q[0]); ed_M(a, a, t);
    ed_A(b, p[0], p[1]); ed_A(t, q[0], q[1]); ed_M(b, b, t);
    ed_M(c, p[3], q[3]); ed_M(c, c, D2);
    ed_M(d, p[2], q[2]); ed_A(d, d, d);
    ed_Z(e, b, a); ed_Z(f, d, c); ed_A(g, d, c); ed_A(h, b, a);
    ed_M(p[0], e, f); ed_M(p[1], h, g); ed_M(p[2], g, f); ed_M(p[3], e, h);
}

static void ed_cswap(gf p[4], gf q[4], uint8_t b) { for (int i = 0; i < 4; i++) ed_sel25519(p[i], q[i], b); }

static void ed_pack(uint8_t *r, gf p[4]) {
    gf tx, ty, zi;
    ed_inv25519(zi, p[2]);
    ed_M(tx, p[0], zi); ed_M(ty, p[1], zi);
    ed_pack25519(r, ty);
    r[31] ^= (uint8_t)(ed_par25519(tx) << 7);
}

static void ed_scalarmult(gf p[4], gf q[4], const uint8_t *s) {
    ed_set25519(p[0], GF0); ed_set25519(p[1], GF1); ed_set25519(p[2], GF1); ed_set25519(p[3], GF0);
    for (int i = 255; i >= 0; --i) {
        uint8_t b = (s[i/8] >> (i & 7)) & 1;
        ed_cswap(p, q, b);
        ed_add(q, p);
        ed_add(p, p);
        ed_cswap(p, q, b);
    }
}

static void ed_scalarbase(gf p[4], const uint8_t *s) {
    gf q[4];
    ed_set25519(q[0], GX); ed_set25519(q[1], GY); ed_set25519(q[2], GF1);
    ed_M(q[3], GX, GY);
    ed_scalarmult(p, q, s);
}

/* reduce a 64-byte little-endian number modulo the group order L */
static void ed_modL(uint8_t *r, int64_t x[64]) {
    int64_t carry, i, j;
    for (i = 63; i >= 32; --i) {
        carry = 0;
        for (j = i - 32; j < i - 12; ++j) {
            x[j] += carry - 16 * x[i] * ED_L[j - (i - 32)];
            carry = (x[j] + 128) >> 8;
            x[j] -= carry * 256;
        }
        x[j] += carry;
        x[i] = 0;
    }
    carry = 0;
    for (j = 0; j < 32; j++) {
        x[j] += carry - (x[31] >> 4) * ED_L[j];
        carry = x[j] >> 8;
        x[j] &= 255;
    }
    for (j = 0; j < 32; j++) x[j] -= carry * ED_L[j];
    for (i = 0; i < 32; i++) { x[i+1] += x[i] >> 8; r[i] = (uint8_t)(x[i] & 255); }
}

static void ed_reduce(uint8_t *r) {
    int64_t x[64];
    for (int i = 0; i < 64; i++) x[i] = (int64_t)(uint64_t)r[i];
    for (int i = 0; i < 64; i++) r[i] = 0;
    ed_modL(r, x);
}

/* decode a public key point and NEGATE it; -1 if it is not on the curve */
static int ed_unpackneg(gf r[4], const uint8_t p[32]) {
    gf t, chk, num, den, den2, den4, den6;
    ed_set25519(r[2], GF1);
    ed_unpack25519(r[1], p);
    ed_S(num, r[1]);
    ed_M(den, num, D);
    ed_Z(num, num, r[2]);
    ed_A(den, r[2], den);
    ed_S(den2, den); ed_S(den4, den2); ed_M(den6, den4, den2);
    ed_M(t, den6, num); ed_M(t, t, den);
    ed_pow2523(t, t);
    ed_M(t, t, num); ed_M(t, t, den); ed_M(t, t, den);
    ed_M(r[0], t, den);
    ed_S(chk, r[0]); ed_M(chk, chk, den);
    if (ed_neq25519(chk, num)) ed_M(r[0], r[0], SQRTM1);
    ed_S(chk, r[0]); ed_M(chk, chk, den);
    if (ed_neq25519(chk, num)) return -1;
    if (ed_par25519(r[0]) == (p[31] >> 7)) ed_Z(r[0], GF0, r[0]);
    ed_M(r[3], r[0], r[1]);
    return 0;
}

/* Returns 1 if `sig` (64 bytes) is a valid Ed25519 signature of msg[0..len)
 * under public key `pk` (32 bytes); 0 otherwise. Also rejects signatures
 * whose S is not reduced (< L), so a signature cannot be re-encoded. */
static int ed25519_verify(const uint8_t sig[64], const uint8_t *msg, size_t len, const uint8_t pk[32]) {
    uint8_t t[32], h[64];
    gf p[4], q[4];

    /* canonical S: compare little-endian S against L */
    int lt = 0;
    for (int i = 31; i >= 0; i--) {
        if (sig[32 + i] < ED_L[i]) { lt = 1; break; }
        if (sig[32 + i] > ED_L[i]) { lt = 0; break; }
    }
    if (!lt) return 0;
    if (ed_unpackneg(q, pk)) return 0;

    sha512_ctx c;
    sha512_init(&c);
    sha512_update(&c, sig, 32);
    sha512_update(&c, pk, 32);
    sha512_update(&c, msg, len);
    sha512_final(&c, h);
    ed_reduce(h);

    ed_scalarmult(p, q, h);
    ed_scalarbase(q, sig + 32);
    ed_add(p, q);
    ed_pack(t, p);
    return ed_verify32(sig, t) == 0;
}

