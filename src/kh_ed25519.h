/*
 * kh_ed25519.h - Ed25519 signature VERIFICATION (and nothing else) for kh.
 *
 * Why this exists: the package registry (packages/registry.json) lists a
 * SHA-256 for every package file, but registry and files live in the same
 * repository, so whoever can change one can change both. A signature made
 * with a private key that is NOT in the repository closes that gap: kh
 * checks registry.json against the public key compiled into kh
 * (src/kh_pubkey.h) before it trusts a single checksum in it.
 *
 * This is a small self-contained verifier following the structure of the
 * public-domain TweetNaCl reference code (field arithmetic on 16 x 16-bit
 * limbs, constant-time-ish ladder). Verification handles only public data
 * (public key, signature, registry text), so side channels are not a concern.
 * It is checked in tests/kh/test_ed25519.c against the RFC 8032 test vectors
 * and against signatures made by an independent implementation (Python
 * `cryptography`), including tampered messages, tampered signatures, wrong
 * keys and non-canonical S values (which are rejected).
 *
 * Constants below are generated by tools/gen_ed25519_consts.py, not typed by hand.
 */
